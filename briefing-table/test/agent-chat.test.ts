/* agent-chat: a session's conversation as chat [agent chat] (Owner 2026-10-05).
 *
 * In-process, no engine: the parser's noise filter on hand-made JSONL (never a
 * real transcript), byte-offset paging across chunk boundaries (including one
 * line bigger than a chunk), the live tail reading only what was appended,
 * codex capture through the real hook handler into the real table, the send
 * path through a stub typer, the Scratchpad through a stub share.
 */
import { mkdtempSync, mkdirSync, writeFileSync, appendFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const root = mkdtempSync(join(tmpdir(), 'wb-agent-chat-'));
process.env.HARBOR_WB_CLAUDE_PROJECTS = join(root, 'projects');
process.env.HARBOR_WB_TABLE = join(root, 'mapping.db');

const chat = await import('../src/engine/agent-chat.ts');
const claudeCode = await import('../src/engine/vendors/claude-code.ts');
const { handleAgentHook } = await import('../src/engine/agent-hook.ts');
const { table } = await import('../src/table/endpoint.ts');

let pass = 0;
let fail = 0;
const ok = (cond: boolean, label: string, detail?: string) => {
  console.log(`${cond ? '  ✓' : '  ✗'} ${label}${detail ? `  (${detail})` : ''}`);
  cond ? pass++ : fail++;
};
const eq = (a: unknown, b: unknown, label: string) => {
  const x = JSON.stringify(a);
  const y = JSON.stringify(b);
  ok(x === y, label, x === y ? undefined : `got ${x}, want ${y}`);
};

const CWD = '/srv/x/project';
const SID = '11111111-2222-3333-4444-555555555555';
const dir = join(root, 'projects', claudeCode.encodeProjectDir(CWD));
mkdirSync(dir, { recursive: true });
const file = join(dir, `${SID}.jsonl`);

let n = 0;
const T = (i: number) => new Date(1_700_000_000_000 + i * 1000).toISOString();
const user = (text: unknown, extra: Record<string, unknown> = {}) => ({ type: 'user', uuid: `u${++n}`, timestamp: T(n), message: { role: 'user', content: text }, ...extra });
const agent = (blocks: unknown[], extra: Record<string, unknown> = {}) => ({ type: 'assistant', uuid: `a${++n}`, timestamp: T(n), message: { role: 'assistant', content: blocks }, ...extra });
const text = (t: string) => ({ type: 'text', text: t });
const tool = (name: string, input: unknown) => ({ type: 'tool_use', id: `tu${++n}`, name, input });
const result = () => user([{ type: 'tool_result', tool_use_id: 'x', content: 'SECRET OUTPUT BODY' }]);
const jl = (rows: unknown[]) => rows.map((r) => JSON.stringify(r)).join('\n') + '\n';

console.log('\n[parser: what is kept, collapsed and dropped]');
const rows = [
  user('<system-reminder>be good</system-reminder>hello there'),
  user('<command-name>/clear</command-name>'),
  user('Caveat: The messages below were generated by the user while running local commands. DO NOT respond.'),
  user('meta text', { isMeta: true }),
  agent([{ type: 'thinking', thinking: 'hmm' }, text('Hi! Looking.')]),
  agent([tool('Bash', { command: 'ls -la /srv' })]),
  result(),
  agent([tool('Read', { file_path: '/srv/x/project/a.ts' }), tool('Read', { file_path: '/srv/x/project/b.ts' })]),
  result(),
  agent([text('Done reading.')]),
  agent([text('side')], { isSidechain: true }),
  { type: 'system', subtype: 'compact_boundary', uuid: 'sys1', timestamp: T(++n) },
  user('This session is being continued from a previous conversation... summary', { isCompactSummary: true }),
  agent([text('API Error: 529 overloaded')], { isApiErrorMessage: true }),
  user('[Request interrupted by user]'),
  user('[chat · @user] please check this Attached: http://share/raw/sessions/me/a%20b.png http://share/raw/sessions/me/c.txt'),
];
const got = chat.parseClaudeLines(rows.map((r, i) => ({ text: JSON.stringify(r), off: i * 100 }))).map((s) => s.item);
eq(got.map((i) => i.role), ['user', 'agent', 'tool', 'agent', 'system', 'system', 'system', 'user'], 'roles: noise gone, tool runs merged, markers in');
eq(got[0].text, 'hello there', 'the reminder is stripped from the typed prompt');
ok(!JSON.stringify(got).includes('SECRET OUTPUT BODY'), 'tool result bodies never appear');
ok(!JSON.stringify(got).includes('hmm') && !JSON.stringify(got).includes('side'), 'thinking and sidechains never appear');
eq(got[2].tools, [{ name: 'Bash', summary: 'ls -la /srv' }, { name: 'Read', summary: 'a.ts' }, { name: 'Read', summary: 'b.ts' }], 'one tool row lists every call with a short summary (3 calls across 2 lines + results)');
eq(got[2].text, 'Ran 3 tools: Bash, Read ×2', 'the tool row reads as one line');
eq(got[4].text, 'Conversation compacted', 'compaction becomes one marker');
ok(!got.some((i) => /continued from a previous/.test(i.text)), 'the compaction summary is dropped');
eq(got[5].text, 'API Error: 529 overloaded', 'an API error is a system marker');
eq(got[6].text, 'Interrupted', 'an interrupt is a marker');
eq(got[7].text, 'please check this', 'our chat frame and the Attached line leave the text');
eq(got[7].files, [{ name: 'a b.png', path: 'http://share/raw/sessions/me/a%20b.png' }, { name: 'c.txt', path: 'http://share/raw/sessions/me/c.txt' }], 'the Attached line becomes files');
eq(chat.parseClaudeLines([{ text: '{"type":"user","message":{"content":"x"', off: 0 }]).length, 0, 'a torn line is skipped');

console.log('\n[paging: tail, before, across chunks, one huge line]');
const pad = 'x'.repeat(1800);
const many: unknown[] = [];
for (let i = 0; i < 400; i++) {
  many.push(user(`q${i}`));
  many.push(agent([text(`a${i} ${pad}`)]));
  if (i === 200) {
    many.push(user([{ type: 'tool_result', tool_use_id: 'big', content: 'Z'.repeat(400 * 1024) }])); // one line > a chunk
  }
}
writeFileSync(file, jl(many));
const read = chat.localReader(file);
const sid = SID;
let page = await chat.pageClaude(read, { sid, limit: 50 });
eq(page.items.length, 50, 'tail page has `limit` items');
eq(page.items[49].text.slice(0, 5), 'a399 ', 'the last item is the newest');
ok(!!page.latest && !!page.before, 'tail page carries latest and before cursors');
const seen: string[] = page.items.map((i) => i.id);
let pages = 1;
while (page.before) {
  page = await chat.pageClaude(read, { sid, before: page.before, limit: 50 });
  seen.unshift(...page.items.map((i) => i.id));
  pages++;
  if (pages > 40) break;
}
eq(seen.length, 800, 'walking `before` to the start yields every item');
eq(new Set(seen).size, 800, '... each exactly once (no overlap, no gap)');
eq([seen[0][0], seen[1][0]], ['u', 'a'], 'oldest first');
ok(pages >= 16, 'it took many pages', `${pages}`);
const bad = await chat.pageClaude(read, { sid, before: 'other-session:123', limit: 50 });
eq(bad.reset, true, 'a cursor from another session id is ignored and reported as reset');
eq((await chat.pageClaude(chat.localReader(join(dir, 'nope.jsonl')), { sid, limit: 50 })).items, [], 'no transcript yet is an empty page, not an error');

console.log('\n[live tail: only the appended bytes are read]');
writeFileSync(file, jl([user('one'), agent([text('two')])]));
const tail0 = await chat.pageClaude(read, { sid, limit: 50 });
eq(tail0.items.map((i) => i.text), ['one', 'two'], 'initial tail');
let bytesRead = 0;
const counting: typeof read = async (o, l) => {
  const r = await read(o, l);
  if (r) bytesRead += Buffer.byteLength(r.data);
  return r;
};
let live = await chat.pageClaude(counting, { sid, after: tail0.latest, limit: 50 });
eq(live.items, [], 'nothing new yet');
eq(live.latest, tail0.latest, '... and the cursor holds');
appendFileSync(file, jl([agent([text('three')])]));
live = await chat.pageClaude(counting, { sid, after: tail0.latest, limit: 50 });
eq(live.items.map((i) => i.text), ['three'], 'an appended line shows up on the next poll');
const half = JSON.stringify(agent([text('four é')]));
appendFileSync(file, half.slice(0, 20));
const live2 = await chat.pageClaude(counting, { sid, after: live.latest, limit: 50 });
eq([live2.items.length, live2.latest], [0, live.latest], 'a half-written line is not shown and the cursor does not move');
appendFileSync(file, half.slice(20) + '\n');
const live3 = await chat.pageClaude(counting, { sid, after: live.latest, limit: 50 });
eq(live3.items.map((i) => i.text), ['four é'], 'once complete it appears (multi-byte text intact)');
ok(bytesRead < 2000, 'polling read a few hundred bytes, not the file', `${bytesRead} B`);
writeFileSync(file, jl([user('fresh')]));
const shrunk = await chat.pageClaude(read, { sid, after: live3.latest, limit: 50 });
eq([shrunk.reset, shrunk.items.map((i) => i.text)], [true, ['fresh']], 'a file that shrank under the cursor starts over, saying so');

console.log('\n[GET chat: vendors]');
const rowsByPane: Record<string, any> = {
  'p-claude': { paneid: 'p-claude', vendor: 'claude-code', session_id: SID, agent: 'proj', state: 'live' },
  'p-claude-new': { paneid: 'p-claude-new', vendor: 'claude-code', session_id: null, agent: 'proj2', state: 'live' },
  'p-gem': { paneid: 'p-gem', vendor: 'gemini-cli', session_id: null, agent: 'gem', state: 'live' },
  'p-sh': { paneid: 'p-sh', vendor: 'cli-manager', session_id: null, agent: null, state: 'live' },
  'p-codex': { paneid: 'p-codex', vendor: 'codex-cli', session_id: null, agent: 'cdx', state: 'live' },
  'p-remote': { paneid: 'p-remote', vendor: 'claude-code', session_id: SID, agent: 'rem', state: 'live' },
};
const typed: Array<[string, string]> = [];
let typerAnswer: 'injected' | 'queued' | 'off' | 'vendor' = 'injected';
let heldAnswer: { reason: string } | null = null;
const live_ = new Set(['p-claude', 'p-codex', 'p-gem', 'p-sh']);
const shareFiles = new Map<string, Array<{ path: string; name: string; kind: string; size: number | null; mtime: number }>>();
const blobs = new Map<string, Buffer>();
let clock = 10;
const share = {
  list: async (f: string) => [...(shareFiles.get(f) ?? [])],
  upload: async (f: string, name: string, type: string, bytes: Buffer) => {
    const arr = shareFiles.get(f) ?? [];
    let final = name;
    for (let i = 1; arr.some((x) => x.name === final); i++) final = name.replace(/(\.[^.]*)?$/, `-${i}$1`);
    arr.push({ path: `${f}/${final}`, name: final, kind: 'file', size: bytes.length, mtime: clock++ });
    shareFiles.set(f, arr);
    blobs.set(`${f}/${final}`, bytes);
    return { ok: true as const, path: `${f}/${final}` };
  },
  refUrl: (ref: string) => `http://share.test/raw/${ref.split('/').map(encodeURIComponent).join('/')}`,
  sanitizeName: (raw: unknown) => (typeof raw === 'string' && raw && !raw.includes('/') && raw !== '..' ? raw : null),
  typeOf: (name: string) => (name.endsWith('.txt') ? 'text/plain' : 'application/octet-stream'),
};
const deps = {
  row: (id: string) => rowsByPane[id],
  isLive: (id: string) => live_.has(id),
  location: (row: any) => (row.paneid === 'p-remote' ? { cwd: CWD, access: { mode: 'unreachable' as const, reason: 'no way to reach that host' } } : { cwd: CWD, access: { mode: 'local' as const } }),
  typer: {
    enqueueChat: (id: string, t: string) => {
      typed.push([id, t]);
      return typerAnswer;
    },
    heldFor: () => heldAnswer,
  },
  share,
  log: () => {},
};
const q = (s = '') => new URLSearchParams(s);
writeFileSync(file, jl([user('hi'), agent([text('hello')])]));
let r = await chat.chatGet('p-claude', q(), deps);
eq([r.status, r.body.supported, (r.body.items as any[]).map((i) => i.role), r.body.vendor], [200, true, ['user', 'agent'], 'claude-code'], 'claude: items from the transcript');
r = await chat.chatGet('p-claude', q(`after=${encodeURIComponent(String(r.body.latest))}`), deps);
eq([r.body.items], [[]], '?after= with the latest cursor: nothing new');
r = await chat.chatGet('nope', q(), deps);
eq(r.status, 404, 'unknown pane: 404');
r = await chat.chatGet('p-claude-new', q(), deps);
eq([r.body.supported, r.body.items], [true, []], 'a claude pane with no banked transcript yet: supported, empty');
r = await chat.chatGet('p-gem', q(), deps);
eq([r.body.supported, /Gemini/.test(String(r.body.reason))], [false, true], 'gemini: supported:false with words');
r = await chat.chatGet('p-sh', q(), deps);
eq([r.body.supported, r.body.reason], [false, 'not an agent CLI'], 'a shell: supported:false, not an agent CLI');
r = await chat.chatGet('p-remote', q(), deps);
eq([r.body.supported, /no way to reach/.test(String(r.body.reason))], [false, true], 'an unreachable host says so in words');

console.log('\n[codex: hooks become items]');
const hookDeps = (state: any = { vendor: 'codex-cli', state: 'live', session_id: 'cccccccc-1' }) => ({
  get: () => state,
  adoptSessionId: () => {},
  activity: { onTurnStart() {}, onResponseDone() {}, onQuestion() {} },
  log: () => {},
  chat: { record: chat.recordHookTurn, gap: chat.noteHookGap },
});
const hook = (paneid: string, body: Record<string, unknown>) => handleAgentHook({ vendor: 'codex-cli', paneid }, body, hookDeps());
r = await chat.chatGet('p-codex', q(), deps);
eq([r.body.supported, r.body.items], [true, []], 'codex before any hook: supported, empty');
hook('p-codex', { hook_event_name: 'UserPromptSubmit', session_id: 'cccccccc-1', prompt: '[chat · @user] add a test' });
hook('p-codex', { hook_event_name: 'Stop', session_id: 'cccccccc-1', last_assistant_message: 'Added the test.' });
hook('p-codex', { hook_event_name: 'Stop', session_id: 'cccccccc-1', last_assistant_message: 'Added the test.' });
hook('p-codex', { hook_event_name: 'PreToolUse', session_id: 'cccccccc-1', tool_name: 'shell' });
r = await chat.chatGet('p-codex', q(), deps);
eq((r.body.items as any[]).map((i) => [i.role, i.text]), [['user', 'add a test'], ['agent', 'Added the test.']], 'codex: prompt (frame stripped) and last message; a repeated Stop is one turn; tool hooks add nothing');
const latest = String(r.body.latest);
hook('p-codex', { hook_event_name: 'UserPromptSubmit', prompt: 'second' });
r = await chat.chatGet('p-codex', q(`after=${latest}`), deps);
eq((r.body.items as any[]).map((i) => i.text), ['second'], 'codex ?after= gives the new turn only');
for (let i = 0; i < 25; i++) hook('p-codex', { hook_event_name: 'UserPromptSubmit', prompt: `m${i}` });
r = await chat.chatGet('p-codex', q('limit=10'), deps);
eq([(r.body.items as any[]).length, !!r.body.before], [10, true], 'codex pages: limit and a before cursor');
r = await chat.chatGet('p-codex', q(`before=${r.body.before}&limit=10`), deps);
eq((r.body.items as any[]).length, 10, 'codex ?before= pages backwards');
rowsByPane['p-codex2'] = { paneid: 'p-codex2', vendor: 'codex-cli', agent: 'cdx2', state: 'live' };
hook('p-codex2', { hook_event_name: 'UserPromptSubmit', session_id: 'cccccccc-2', text: 'unknown field name' });
r = await chat.chatGet('p-codex2', q(), deps);
eq([r.body.supported, /did not send the message text/.test(String(r.body.reason))], [false, true], 'a hook that carries no text field: supported:false with the reason');
for (let i = 0; i < 2005; i++) table.appendPaneChat('capped', 'user', `t${i}`);
const capped = table.listPaneChat('capped', { limit: 5000 });
eq([capped.rows.length, capped.rows[0].text], [2000, 't5'], 'the per-pane log is capped at 2000, oldest dropped');

console.log('\n[POST chat: through the typer]');
let s = await chat.chatSend('p-claude', { text: 'hello agent' }, deps);
eq([s.status, s.body.state, typed.at(-1)], [200, 'typed', ['p-claude', 'hello agent']], 'idle: typed, state typed');
typerAnswer = 'queued';
heldAnswer = { reason: 'draft' };
s = await chat.chatSend('p-claude', { text: 'later' }, deps);
eq([s.body.state, s.body.reason], ['held', 'draft'], 'a draft in the input: held, with the reason');
heldAnswer = null;
s = await chat.chatSend('p-claude', { text: 'later2' }, deps);
eq(s.body.state, 'queued', 'queued with nothing blocking yet: queued');
typerAnswer = 'injected';
eq((await chat.chatSend('p-claude-new', { text: 'x' }, deps)).status, 409, 'a session that is not running: 409');
eq((await chat.chatSend('p-sh', { text: 'x' }, deps)).status, 409, 'a shell: no chat to send to');
eq((await chat.chatSend('p-claude', {}, deps)).status, 400, 'no text and no files: 400');
eq((await chat.chatSend('nope', { text: 'x' }, deps)).status, 404, 'unknown pane: 404');
eq((await chat.chatSend('p-claude', { text: 'x'.repeat(2000) }, deps)).status, 413, 'a message too long to type is refused with its length, never cut');
typerAnswer = 'off';
eq((await chat.chatSend('p-claude', { text: 'x' }, deps)).status, 409, 'typing switched off: 409 in words');
typerAnswer = 'injected';

console.log('\n[Scratchpad + attachments]');
let sp = await chat.scratchList('p-claude', deps);
eq([sp.status, sp.body.folder, sp.body.files], [200, 'sessions/proj', []], 'an empty Scratchpad lists under sessions/<agent slug>');
const up1 = await chat.scratchUpload('p-claude', 'notes.txt', 'text/plain', Buffer.from('hello'), deps);
eq([up1.status, up1.body.path, up1.body.raw], [200, 'sessions/proj/notes.txt', '/api/sessions/p-claude/scratchpad/raw/notes.txt'], 'upload lands in the session folder and names its raw route');
const up2 = await chat.scratchUpload('p-claude', 'notes.txt', 'text/plain', Buffer.from('again'), deps);
eq(up2.body.name, 'notes-1.txt', 'a name collision is passed through (never overwrites)');
await chat.scratchUpload('p-claude', 'shot.png', '', Buffer.from('png'), deps);
sp = await chat.scratchList('p-claude', deps);
eq((sp.body.files as any[]).map((f) => f.name), ['shot.png', 'notes-1.txt', 'notes.txt'], 'newest first');
eq((await chat.scratchUpload('p-claude', null, '', Buffer.from('x'), deps)).status, 400, 'no x-filename: 400');
eq((await chat.scratchUpload('p-claude', 'a.txt', '', Buffer.alloc(0), deps)).status, 400, 'empty body: 400');
eq((await chat.scratchList('p-sh', deps)).status, 409, 'no agent slug, no Scratchpad (409 in words)');
const rawOk = chat.scratchRawRef('p-claude', 'notes.txt', deps);
eq(rawOk, { ref: 'sessions/proj/notes.txt' }, 'raw ref resolves inside the session folder');
eq((chat.scratchRawRef('p-claude', '../x', deps) as any).status, 400, 'a path in the raw name is refused');
s = await chat.chatSend('p-claude', { text: 'see these', files: ['notes.txt', 'shot.png'] }, deps);
const sentLine = typed.at(-1)![1];
eq(sentLine, 'see these Attached: http://share.test/raw/sessions/proj/notes.txt http://share.test/raw/sessions/proj/shot.png', 'files become one "Attached:" line of absolute references');
eq((await chat.chatSend('p-claude', { text: 'x', files: ['missing.txt'] }, deps)).status, 400, 'a file not in the Scratchpad: 400, named');
const echoed = chat.parseClaudeLine(JSON.stringify(user(`[chat · @user] ${sentLine}`)), 0)[0];
eq([echoed.text, echoed.files?.map((f) => f.name)], ['see these', ['notes.txt', 'shot.png']], 'the transcript echo of that turn shows the text and the files');

try { rmSync(root, { recursive: true, force: true }); } catch { /* Windows: the store still holds the db (EPERM) */ }
console.log(`\n${'='.repeat(40)}\nPASS ${pass}  FAIL ${fail}`);
if (fail) {
  process.exit(1);
}
console.log('all green');
