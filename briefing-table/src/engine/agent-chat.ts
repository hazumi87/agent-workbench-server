/* ------------------------------------------------------- the line parser -- */

const REMINDER_RE = /<system-reminder>[\s\S]*?<\/system-reminder>/g;
const HOOK_OUT_RE = /<user-prompt-submit-hook>[\s\S]*?<\/user-prompt-submit-hook>/g;
const WRAPPER_RE = /^\s*<(command-name|command-message|command-args|local-command-stdout|local-command-stderr|local-command-caveat|bash-input|bash-stdout|bash-stderr)>/;
const CAVEAT_RE = /^\s*Caveat: The messages below were generated by the user while running local commands/;
/** Our own typed frame (room-typer.frameChat): never shown as part of the person's words. */
const CHAT_FRAME_RE = /^\[chat · @user(?: · (voice))?\] /;
/** Only the plain frame: a voice frame is kept when a Codex hook turn is stored, so the reader can still see it. */
const PLAIN_FRAME_RE = /^\[chat · @user\] /;
const ATTACHED_RE = /\s*Attached: (https?:\/\/\S+(?: https?:\/\/\S+)*)\s*$/;

function str(v: unknown): string {
  return typeof v === 'string' ? v : '';
}

/** A person's turn as it should read: reminders and hook output removed, our chat
 *  frame stripped, the "Attached:" line turned into `files`. Null = not a chat turn. */
export function cleanUserText(raw: string): { text: string; files?: ChatItem['files']; via?: 'voice' } | { marker: string } | null {
  if (WRAPPER_RE.test(raw) || CAVEAT_RE.test(raw)) {
    return null;
  }
  let t = raw.replace(REMINDER_RE, '').replace(HOOK_OUT_RE, '').trim();
  if (!t) {
    return null;
  }
  if (t.startsWith('[Request interrupted by user')) {
    return { marker: 'Interrupted' };
  }
  const via = CHAT_FRAME_RE.exec(t)?.[1] === 'voice' ? ('voice' as const) : undefined;
  t = t.replace(CHAT_FRAME_RE, '');
  let files: ChatItem['files'];
  const m = ATTACHED_RE.exec(t);
  if (m) {
    files = m[1].split(' ').map((u) => {
      let name = u;
      try {
        name = decodeURIComponent(basename(new URL(u).pathname));
      } catch {
        /* keep the raw url as the name */
      }
      return { name, path: u };
    });
    t = t.slice(0, m.index).trim();
  }
  return { text: t, ...(files ? { files } : {}), ...(via ? { via } : {}) };
}

/** A few words saying what one tool call did — never its output. */
export function toolSummary(name: string, input: unknown): string {
  const i = (input && typeof input === 'object' ? input : {}) as Record<string, unknown>;
  const pick = (...keys: string[]): string => {
    for (const k of keys) {
      if (typeof i[k] === 'string' && i[k]) {
        return i[k] as string;
      }
    }
    return '';
  };
  let s = '';
  if (/^(Read|Edit|Write|MultiEdit|NotebookEdit)$/.test(name)) {
    s = basename(pick('file_path', 'notebook_path'));
  } else if (name === 'Bash') {
    s = pick('command');
  } else if (name === 'Grep' || name === 'Glob') {
    s = pick('pattern');
  } else if (name === 'Task' || name === 'Agent') {
    s = pick('description');
  } else if (name === 'WebFetch') {
    s = pick('url');
  } else {
    s = pick('description', 'command', 'query', 'path', 'file_path', 'url');
  }
  s = s.replace(/\s+/g, ' ').trim();
  return s.length > 80 ? `${s.slice(0, 79)}…` : s;
}

/** One transcript line to zero or more items (tool rows are merged afterwards). */
export function parseClaudeLine(raw: string, off: number): ChatItem[] {
  let o: any;
  try {
    o = JSON.parse(raw);
  } catch {
    return []; // a torn or foreign line is not a turn
  }
  if (!o || typeof o !== 'object' || o.isSidechain === true || o.isMeta === true) {
    return [];
  }
  const id = str(o.uuid) || `o${off}`;
  const ts = Date.parse(str(o.timestamp)) || 0;
  if (o.type === 'system') {
    if (o.subtype === 'compact_boundary') {
      return [{ id, role: 'system', text: 'Conversation compacted', ts }];
    }
    if (o.subtype === 'api_error') {
      return [{ id, role: 'system', text: 'API error', ts }];
    }
    return [];
  }
  const content = o.message?.content;
  if (o.type === 'user') {
    if (o.isCompactSummary === true) {
      return [];
    }
    const text =
      typeof content === 'string'
        ? content
        : Array.isArray(content)
          ? content.filter((b: any) => b?.type === 'text').map((b: any) => str(b.text)).join('\n\n')
          : '';
    if (!text) {
      return []; // tool results and images only
    }
    const c = cleanUserText(text);
    if (!c) {
      return [];
    }
    if ('marker' in c) {
      return [{ id, role: 'system', text: c.marker, ts }];
    }
    return [{ id, role: 'user', text: c.text, ts, ...(c.files ? { files: c.files } : {}), ...(c.via ? { meta: { via: c.via } } : {}) }];
  }
  if (o.type === 'assistant') {
    const blocks: any[] = typeof content === 'string' ? [{ type: 'text', text: content }] : Array.isArray(content) ? content : [];
    if (o.isApiErrorMessage === true) {
      const msg = blocks.map((b) => str(b?.text)).join(' ').replace(/\s+/g, ' ').trim();
      return [{ id, role: 'system', text: msg ? (msg.length > 200 ? `${msg.slice(0, 199)}…` : msg) : 'API error', ts }];
    }
    const out: ChatItem[] = [];
    const text = blocks
      .filter((b) => b?.type === 'text')
      .map((b) => str(b.text).trim())
      .filter((t) => t && t !== 'No response requested.')
      .join('\n\n');
    if (text) {
      out.push({ id, role: 'agent', text, ts });
    }
    const tools = blocks.filter((b) => b?.type === 'tool_use').map((b) => ({ name: str(b.name) || 'tool', summary: toolSummary(str(b.name), b.input) }));
    if (tools.length) {
      out.push({ id: `${id}:t`, role: 'tool', text: '', ts, tools });
    }
    return out;
  }
  return [];
}

function toolText(tools: Array<{ name: string }>): string {
  const counts = new Map<string, number>();
  for (const t of tools) {
    counts.set(t.name, (counts.get(t.name) ?? 0) + 1);
  }
  const names = [...counts].map(([n, c]) => (c > 1 ? `${n} ×${c}` : n)).join(', ');
  return `Ran ${tools.length} tool${tools.length === 1 ? '' : 's'}: ${names}`;
}

interface Sourced {
  item: ChatItem;
  off: number;
}

/** Lines (oldest first, each with its byte offset) to items, adjacent tool
 *  rows merged into one. Tool-result lines yield nothing, so a burst stays adjacent. */
export function parseClaudeLines(lines: Array<{ text: string; off: number }>): Sourced[] {
  const out: Sourced[] = [];
  for (const l of lines) {
    for (const item of parseClaudeLine(l.text, l.off)) {
      const prev = out[out.length - 1];
      if (item.role === 'tool' && prev && prev.item.role === 'tool') {
        prev.item.tools = [...(prev.item.tools ?? []), ...(item.tools ?? [])].slice(0, TOOLS_PER_ROW);
        continue;
      }
      out.push({ item, off: l.off });
    }
  }
  for (const s of out) {
    if (s.item.role === 'tool') {
      s.item.text = toolText(s.item.tools ?? []);
    }
  }
  return out;
}

/* ----------------------------------------------------------- byte readers -- */

/** A byte slice of one transcript as utf-8, plus the file's size. Null = the file is not there (yet). */
export type SliceReader = (offset: number, limit: number) => Promise<{ data: string; size: number } | null>;

export function localReader(path: string): SliceReader {
  return async (offset, limit) => {
    let fh;
    try {
      fh = await open(path, 'r');
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === 'ENOENT') {
        return null;
      }
      throw e;
    }
    try {
      const size = (await fh.stat()).size;
      const len = Math.max(0, Math.min(limit, size - offset));
      const buf = Buffer.alloc(len);
      const { bytesRead } = await fh.read(buf, 0, len, offset);
      return { data: buf.toString('utf8', 0, bytesRead), size };
    } finally {
      await fh.close();
    }
  };
}

const SAFE_ID = /^[0-9A-Za-z][0-9A-Za-z-]{7,63}$/;

export function sshReader(alias: string, projectDir: string, sessionId: string): SliceReader {
  const enc = claudeCode.encodeProjectDir(projectDir);
  return (offset, limit) =>
    new Promise((resolve, reject) => {
      if (!SAFE_ID.test(sessionId) || !/^[A-Za-z0-9-]+$/.test(enc)) {
        resolve(null);
        return;
      }
      const f = `~/.claude/projects/${enc}/${sessionId}.jsonl`;
      const cmd = `f=${f}; [ -f "$f" ] || { echo MISSING; exit 0; }; stat -c %s "$f"; tail -c +${Math.floor(offset) + 1} "$f" | head -c ${Math.floor(limit)}`;
      execFile(sshBinary(), [alias, cmd], { timeout: 15_000, windowsHide: true, maxBuffer: limit + 4096, encoding: 'utf8' }, (err, stdout) => {
        if (err) {
          reject(err);
          return;
        }
        const nl = stdout.indexOf('\n');
        const head = nl < 0 ? stdout : stdout.slice(0, nl);
        if (head.trim() === 'MISSING') {
          resolve(null);
          return;
        }
        resolve({ size: Number(head) || 0, data: nl < 0 ? '' : stdout.slice(nl + 1) });
      });
    });
}

export function agentReader(host: string, projectDir: string, sessionId: string): SliceReader {
  return async (offset, limit) => {
    try {
      const r = await agentFs.read(host, projectDir, `${sessionId}.jsonl`, { offset, limit });
      return { data: r.data, size: r.size };
    } catch (e) {
      if (e instanceof agentFs.AgentFsError && /enoent|not found|no such/i.test(`${(e as Error).message}`)) {
        return null;
      }
      throw e;
    }
  };
}

/* ------------------------------------------------------------ the pagers -- */

const byteLen = (s: string): number => Buffer.byteLength(s, 'utf8');

/** Split `text` (complete lines ending at byte offset `endOff`) into lines with offsets, computed from the END. */
function linesEndingAt(text: string, endOff: number): Array<{ text: string; off: number }> {
  const out: Array<{ text: string; off: number }> = [];
  let off = endOff;
  const parts = text.split('\n');
  parts.pop(); // text ends with '\n': the last element is empty
  for (let i = parts.length - 1; i >= 0; i--) {
    off -= byteLen(parts[i]) + 1;
    if (parts[i]) {
      out.unshift({ text: parts[i], off });
    }
  }
  return out;
}

const cursorOf = (sid: string, off: number): string => `${sid}:${off}`;
function offsetOf(cursor: string | null | undefined, sid: string): number | null | 'foreign' {
  if (!cursor) {
    return null;
  }
  const i = cursor.lastIndexOf(':');
  const off = Number(cursor.slice(i + 1));
  if (i < 0 || !Number.isInteger(off) || off < 0) {
    return 'foreign';
  }
  return cursor.slice(0, i) === sid ? off : 'foreign';
}

export interface ClaudePageIn {
  sid: string;
  before?: string | null;
  after?: string | null;
  limit: number;
}

/** One page of a Claude transcript. Reads only what the page needs. */
export async function pageClaude(read: SliceReader, q: ClaudePageIn): Promise<Pick<ChatPage, 'items' | 'before' | 'latest' | 'reset'>> {
  const empty = { items: [] as ChatItem[], before: null, latest: null };
  const a = offsetOf(q.after, q.sid);
  const b = offsetOf(q.before, q.sid);
  const reset = a === 'foreign' || b === 'foreign';

  if (typeof a === 'number') {
    /* THE LIVE TAIL: [cursor, size) only. A cursor past the end means the file
       shrank under us — start over from the tail. */
    const items: ChatItem[] = [];
    let pos = a;
    let first = true;
    let chunk = CHUNK;
    for (let scanned = 0; scanned < MAX_SCAN; ) {
      const r = await read(pos, chunk);
      if (!r) {
        return empty;
      }
      if (first && a > r.size) {
        return { ...(await pageClaude(read, { sid: q.sid, limit: q.limit })), reset: true };
      }
      first = false;
      const cut = r.data.lastIndexOf('\n');
      if (cut < 0) {
        if (pos + chunk >= r.size && byteLen(r.data) < chunk) {
          break; // a line still being written
        }
        if (chunk >= MAX_LINE) {
          break; // one line larger than we will read: the tail waits here
        }
        chunk *= 2; // a big tool result is one line: read more of it
        continue;
      }
      const whole = r.data.slice(0, cut + 1);
      items.push(...parseClaudeLines(linesEndingAt(whole, pos + byteLen(whole))).map((x) => x.item));
      pos += byteLen(whole);
      scanned += byteLen(whole);
      if (pos >= r.size) {
        break;
      }
    }
    return { items, before: null, latest: cursorOf(q.sid, pos), ...(reset ? { reset } : {}) };
  }

  /* BACKWARDS (the tail page when no cursor, `before` otherwise): chunks from
     the end until enough items, the start of the file, or the scan budget. */
  let end: number;
  let latest: string | null = null;
  if (typeof b === 'number') {
    end = b;
  } else {
    const probe = await read(0, 1);
    if (!probe) {
      return empty;
    }
    end = probe.size;
    // trim a half-written last line off the tail
    const tail = await read(Math.max(0, end - CHUNK), Math.min(CHUNK, end));
    if (!tail) {
      return empty;
    }
    const cut = tail.data.lastIndexOf('\n');
    if (cut >= 0 && cut + 1 < tail.data.length) {
      end -= byteLen(tail.data.slice(cut + 1));
    }
    latest = cursorOf(q.sid, end);
  }
  const lines: Array<{ text: string; off: number }> = [];
  let cursor = end;
  let scanned = 0;
  let atStart = cursor === 0;
  let items: Sourced[] = [];
  let chunk = CHUNK;
  while (!atStart && scanned < MAX_SCAN) {
    const s = Math.max(0, cursor - chunk);
    const r = await read(s, cursor - s);
    if (!r) {
      return empty;
    }
    let text = r.data;
    const chunkEnd = cursor;
    if (s > 0) {
      const nl = text.indexOf('\n');
      if (nl < 0 || nl + 1 >= text.length) {
        // no complete line in this window (its only newline is the one that ends it)
        if (chunk >= MAX_LINE) {
          break; // one line larger than we will read: stop going back here
        }
        chunk *= 2; // a big tool result is one line: read more of it
        continue;
      }
      text = text.slice(nl + 1);
    }
    lines.unshift(...linesEndingAt(text, chunkEnd));
    scanned += cursor - s;
    // the next chunk ends at the first line boundary we kept
    cursor = lines.length ? lines[0].off : s;
    if (s === 0) {
      atStart = true;
    }
    items = parseClaudeLines(lines);
    if (items.length > q.limit + 8) {
      break;
    }
  }
  if (!items.length) {
    items = parseClaudeLines(lines);
  }
  let kept = items.slice(-q.limit);
  // never split one line's items across two pages
  if (kept.length < items.length) {
    const edge = kept[0].off;
    let i = items.length - kept.length;
    while (i > 0 && items[i - 1].off === edge) {
      i--;
    }
    kept = items.slice(i);
  }
  const more = kept.length < items.length || !atStart;
  return {
    items: kept.map((s) => s.item),
    before: more && kept.length ? cursorOf(q.sid, kept[0].off) : null,
    latest,
    ...(reset ? { reset } : {}),
  };
}

