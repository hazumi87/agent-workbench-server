const err = (status: number, error: string, field?: string): Result => ({ status, body: { error, ...(field ? { field } : {}) } });

export const TYPE_MAX = 1500;

function clampLimit(raw: unknown): number {
  const n = Number(raw);
  return Number.isInteger(n) && n > 0 ? Math.min(n, MAX_LIMIT) : DEFAULT_LIMIT;
}

export async function chatGet(paneid: string, query: URLSearchParams, deps: ChatDeps): Promise<Result> {
  const row = deps.row(paneid);
  if (!row) {
    return err(404, `no session ${paneid}`, 'paneid');
  }
  const vendor = row.vendor || 'unknown';
  const page = (p: Partial<ChatPage>): Result => ({
    status: 200,
    body: { paneid, vendor, supported: true, items: [], before: null, latest: null, ...p },
  });
  const unsupported = (reason: string): Result => page({ supported: false, reason });
  const limit = clampLimit(query.get('limit'));
  const before = query.get('before');
  const after = query.get('after');

  if (vendor === 'gemini-cli') {
    return unsupported('Gemini conversations are not readable yet');
  }
  if (vendor === 'codex-cli') {
    const gaps = hookGaps.get(paneid);
    const r = pageCodex(paneid, { before, after, limit });
    if (!r.items.length && gaps && gaps.size) {
      return unsupported("Codex's hooks did not send the message text, so this conversation cannot be shown");
    }
    return page(r);
  }
  if (vendor !== 'claude-code') {
    return unsupported('not an agent CLI');
  }
  const sid = row.session_id;
  if (!sid || !SAFE_ID.test(sid)) {
    return page({ note: 'this session has no transcript yet' });
  }
  const loc = deps.location(row);
  if (!loc) {
    return unsupported('the session’s folder is not known, so its conversation cannot be found');
  }
  let read: SliceReader;
  switch (loc.access.mode) {
    case 'local':
      read = localReader(claudeCode.transcriptPath(loc.cwd, sid));
      break;
    case 'ssh':
      read = sshReader(loc.access.sshAlias, loc.cwd, sid);
      break;
    case 'agent':
      read = agentReader(loc.access.host, loc.cwd, sid);
      break;
    default:
      return unsupported(`the conversation cannot be read from here: ${loc.access.reason}`);
  }
  try {
    const r = await pageClaude(read, { sid, before, after, limit });
    return page(r);
  } catch (e) {
    deps.log(`agent-chat ${paneid}: read failed: ${(e as Error).message}`);
    return err(502, `could not read the conversation: ${(e as Error).message}`, 'transcript');
  }
}

/* ---------------------------------------------------------------- Search -- */

const SEARCH_PAGES = 30; // at most 30 pages of MAX_LIMIT back (about 6000 messages) per search

/** SEARCH an agent's conversation [search] Owner 2026-10-06 (BUILD-HANDOFF §1.K): newest first,
 *  every word, the person's and the agent's words (not tool rows). Pages back through the same
 *  reader the Chat tab uses. Each hit carries `at`, the `before` cursor of the page it was found
 *  on (null = the newest page), so the page can load that page and jump to the hit. `more` = the
 *  scan stopped at its budget with history left. */
export async function chatSearch(paneid: string, query: URLSearchParams, deps: ChatDeps): Promise<Result> {
  const words = searchTerms(query.get('q') ?? '');
  const want = Math.max(1, Math.min(200, Number(query.get('limit')) || 50));
  const results: Array<{ id: string; role: ChatItem['role']; ts: number; snippet: SnipPart[]; at: string | null }> = [];
  if (!words.length) {
    return { status: 200, body: { paneid, q: '', results, more: false } };
  }
  let before: string | null = null;
  let more = false;
  for (let page = 0; page < SEARCH_PAGES; page++) {
    const qs = new URLSearchParams({ limit: String(MAX_LIMIT) });
    if (before) qs.set('before', before);
    const r = await chatGet(paneid, qs, deps);
    const body = r.body as Partial<ChatPage> & { error?: string };
    if (r.status !== 200 || body.supported === false) {
      return page === 0 ? r : { status: 200, body: { paneid, q: words.join(' '), results, more: false } };
    }
    const items = (body.items ?? []).slice().reverse(); // newest first within the page
    for (const it of items) {
      if ((it.role === 'user' || it.role === 'agent') && matchesAll(it.text, words)) {
        results.push({ id: it.id, role: it.role, ts: it.ts, snippet: searchSnippet(it.text, words), at: before });
        if (results.length >= want) {
          return { status: 200, body: { paneid, q: words.join(' '), results, more: true } };
        }
      }
    }
    if (!body.before || body.before === before) {
      break;
    }
    before = body.before;
    more = page === SEARCH_PAGES - 1;
  }
  return { status: 200, body: { paneid, q: words.join(' '), results, more } };
}

/* ------------------------------------------------------------ Scratchpad -- */

/** `sessions/<agent slug>` on the share root: the room-assets storage, one folder per session. */
export function scratchFolder(row: PaneRow): string | null {
  const slug = (row.agent ?? '').trim();
  return /^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug) && slug.length <= 64 ? `sessions/${slug}` : null;
}

const NO_SLUG = 'this session has no agent name yet, so it has no Scratchpad';

export async function scratchList(paneid: string, deps: ChatDeps): Promise<Result> {
  const row = deps.row(paneid);
  if (!row) {
    return err(404, `no session ${paneid}`, 'paneid');
  }
  const folder = scratchFolder(row);
  if (!folder) {
    return err(409, NO_SLUG, 'agent');
  }
  let files;
  try {
    files = await deps.share.list(folder);
  } catch (e) {
    // could not tell: never an empty list, which would read as "no files"
    return err((e as Error).name === 'ShareNotConfigured' ? 503 : 502, `could not read agent-share: ${(e as Error).message}`, 'agent-share');
  }
  const base = `/api/sessions/${encodeURIComponent(paneid)}/scratchpad/raw/`;
  return {
    status: 200,
    body: {
      folder,
      files: files
        .sort((a, b) => b.mtime - a.mtime)
        .map((f) => ({
          name: f.name,
          path: f.path,
          url: deps.share.refUrl(f.path),
          raw: base + encodeURIComponent(f.name),
          kind: f.kind,
          size: f.size,
          type: deps.share.typeOf(f.name),
          addedAt: Math.round(f.mtime * 1000),
        })),
    },
  };
}

export async function scratchUpload(paneid: string, rawName: string | null, contentType: string, bytes: Buffer, deps: ChatDeps): Promise<Result> {
  const row = deps.row(paneid);
  if (!row) {
    return err(404, `no session ${paneid}`, 'paneid');
  }
  const folder = scratchFolder(row);
  if (!folder) {
    return err(409, NO_SLUG, 'agent');
  }
  const name = deps.share.sanitizeName(rawName);
  if (!name) {
    return err(400, 'x-filename names the file (a basename, percent-encoded UTF-8)', 'x-filename');
  }
  if (!bytes.length) {
    return err(400, 'the body is the file and it is empty', 'body');
  }
  const ct = contentType.split(';')[0].trim().toLowerCase();
  const type = /^[a-z0-9.+-]+\/[a-z0-9.+-]+$/.test(ct) && ct !== 'application/octet-stream' ? ct : deps.share.typeOf(name);
  const up = await deps.share.upload(folder, name, type, bytes);
  if (!up.ok) {
    deps.log(`agent-chat ${paneid}: scratchpad upload to ${folder} failed: ${up.error}`);
    return err(up.status, up.error, up.field);
  }
  const stored = up.path.slice(up.path.lastIndexOf('/') + 1);
  deps.log(`agent-chat ${paneid}: scratchpad ${up.path} (${bytes.length} B)`);
  return {
    status: 200,
    body: {
      name: stored,
      path: up.path,
      url: deps.share.refUrl(up.path),
      raw: `/api/sessions/${encodeURIComponent(paneid)}/scratchpad/raw/${encodeURIComponent(stored)}`,
      size: bytes.length,
      type,
    },
  };
}

/** The share ref of one Scratchpad file for the raw route, or a refusal. */
export function scratchRawRef(paneid: string, name: string, deps: ChatDeps): { ref: string } | Result {
  const row = deps.row(paneid);
  if (!row) {
    return err(404, `no session ${paneid}`, 'paneid');
  }
  const folder = scratchFolder(row);
  if (!folder) {
    return err(409, NO_SLUG, 'agent');
  }
  if (!name || name === '.' || name === '..' || name.includes('/') || name.includes(String.fromCharCode(92))) {
    return err(400, 'a Scratchpad file is named by its bare file name', 'name');
  }
  return { ref: `${folder}/${name}` };
}

/* ------------------------------------------------------------------ send -- */

/** Appended to the FIRST chat message of a pane (room welcome, Owner 2026-10-05). */
export const CHAT_NOTE = ' (This is a direct chat with the user: answer normally in this session; do not use room_post or Fabric for it.)';

export async function chatSend(paneid: string, body: Record<string, unknown>, deps: ChatDeps): Promise<Result> {
  const row = deps.row(paneid);
  if (!row) {
    return err(404, `no session ${paneid}`, 'paneid');
  }
  const vendor = row.vendor || 'unknown';
  if (vendor !== 'claude-code' && vendor !== 'codex-cli' && vendor !== 'gemini-cli') {
    return err(409, 'not an agent CLI: there is no chat to send to', 'vendor');
  }
  if (!deps.isLive(paneid)) {
    return err(409, 'this session is not running; restore it first', 'state');
  }
  const text = typeof body.text === 'string' ? body.text.trim() : '';
  const names = Array.isArray(body.files) ? body.files : [];
  if (body.files !== undefined && !Array.isArray(body.files)) {
    return err(400, 'files is a list of Scratchpad file names', 'files');
  }
  if (!text && !names.length) {
    return err(400, 'text is the message (or files, the attachments)', 'text');
  }
  let line = text;
  if (names.length) {
    const folder = scratchFolder(row);
    if (!folder) {
      return err(409, NO_SLUG, 'agent');
    }
    let have: Set<string>;
    try {
      have = new Set((await deps.share.list(folder)).map((f) => f.name));
    } catch (e) {
      return err((e as Error).name === 'ShareNotConfigured' ? 503 : 502, `could not read agent-share: ${(e as Error).message}`, 'agent-share');
    }
    const urls: string[] = [];
    for (const n of names) {
      if (typeof n !== 'string' || !have.has(n)) {
        return err(400, `${typeof n === 'string' ? `"${n}"` : 'a file'} is not in this session's Scratchpad`, 'files');
      }
      urls.push(deps.share.refUrl(`${folder}/${n}`));
    }
    line = `${text ? `${text} ` : ''}Attached: ${urls.join(' ')}`;
  }
  /* [basic] a typed /command in the agent chat goes to the agent verbatim with the typed
     marker, like a Basic room line (agent-commands.ts); the full edition is unchanged */
  const word = isBasic() ? slashWord(text) : null;
  if (word) {
    line += ` ${typedMarker(word)}`;
  }
  /* First chat message to a pane carries a one-sentence note [room welcome, Owner 2026-10-05]:
     a Codex agent in its own direct chat answered through Fabric. Claimed per pane in the
     table; given back below if the line did not go. */
  const noted = deps.noteChat ? deps.noteChat.claim(paneid) : false;
  if (noted) {
    line += CHAT_NOTE;
  }
  if (line.length > TYPE_MAX - 32) {
    if (noted) deps.noteChat!.release(paneid);
    return err(413, `the message is ${line.length} characters; at most ${TYPE_MAX - 32} can be typed into the session at once`, 'text');
  }
  /* [concierge] a line the person SPOKE: the route allows it on a person's credential only */
  const via = body.via === 'voice' ? ('voice' as const) : null;
  const r = via ? deps.typer.enqueueChat(paneid, line, via) : deps.typer.enqueueChat(paneid, line);
  if (noted && (r === 'off' || r === 'vendor')) deps.noteChat!.release(paneid);
  deps.log(`agent-chat ${paneid}: send ${r} (${line.length} chars)`);
  if (r === 'off') {
    return { status: 409, body: { ok: false, error: 'typing into sessions is switched off on this engine', field: 'typer' } };
  }
  if (r === 'vendor') {
    return { status: 409, body: { ok: false, error: 'this CLI cannot be typed into', field: 'vendor' } };
  }
  if (r === 'injected') {
    return { status: 200, body: { ok: true, state: 'typed' } };
  }
  const held = deps.typer.heldFor(paneid);
  if (held && held.reason !== 'pending') {
    return { status: 200, body: { ok: true, state: 'held', reason: held.reason, held } };
  }
  return { status: 200, body: { ok: true, state: 'queued', ...(held ? { held } : {}) } };
}
