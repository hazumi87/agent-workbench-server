/** E1 "no room tools" roster state: tools = room | none | unknown (three outcomes, never two). the design notes section 6. */
const bt = await import('../src/engine/bt-tools.ts');
let passed = 0;
let failed = 0;
const ok = (c: unknown, m: string): void => { if (c) { passed++; console.log(`  ok ${m}`); } else { failed++; console.log(`  X  ${m}`); } };

bt._reset();
const T0 = 1_000_000;
ok(bt.state('p1', T0).tools === 'unknown', 'a pane nobody planned anything for: unknown');
bt.plan('p1', T0);
ok(bt.state('p1', T0 + 5_000).tools === 'unknown', 'planned and young: unknown (too early to tell)');
const late = bt.state('p1', T0 + bt.TOOLS_SECS * 1000 + 1);
ok(late.tools === 'none' && late.reason === 'never-connected', `planned, older than ${bt.TOOLS_SECS} s, no call: none, reason never-connected`);
bt.noteCall('p1', T0 + 40_000);
ok(bt.state('p1', T0 + 90_000).tools === 'room', 'after a call on /mcp: room');
ok(bt.state('p1', T0 + 90_000).reason === undefined, '...with no reason');
bt.noteCall('nobody', T0);
ok(bt.state('nobody', T0).tools === 'unknown', 'a call from a pane that was never planned does not invent a state');
bt.plan('p2', T0);
bt.drop('p2');
ok(bt.state('p2', T0 + 99_000).tools === 'unknown', 'a pane that ended is forgotten');
bt.plan('p3', T0);
bt.notPlanned('p3', 'vendor-unsupported');
ok(bt.state('p3', T0 + 99_000).tools === 'unknown' && bt.state('p3', T0 + 99_000).reason === 'vendor-unsupported', 'not planned: unknown, and it says why');
bt.plan('p4', T0);
ok(bt.isPlanned('p4') && !bt.isPlanned('p3'), 'isPlanned says whether injection was planned (the welcome text reads it)');
ok(bt.shouldSayNone('p4', T0 + 99_000) === true && bt.shouldSayNone('p4', T0 + 99_001) === false, 'the room is told "no room tools" ONCE per pane');
let wakes = 0;
bt.onListed(() => { wakes++; });
bt.plan('ready', T0);
bt.noteCall('ready', T0 + 1);
ok(bt.listedAt('ready', 1) === null, 'a generic MCP call is not a startup-ready enumeration');
bt.noteListed('ready', 1, T0 + 2);
bt.noteListed('ready', 1, T0 + 3);
ok(bt.listedAt('ready', 1) === T0 + 2 && wakes === 1, 'first enumeration wakes once and duplicate lists do not postpone readiness');
ok(bt.listedAt('ready', 2) === null, 'readiness is bound to the token generation');
bt.plan('ready', T0 + 4);
ok(bt.listedAt('ready', 1) === null, 'a fresh launch clears enumeration evidence');
bt.noteListed('ready', 2, T0 + 5);
bt.notPlanned('ready', 'no-token');
ok(bt.listedAt('ready', 2) === null, 'failed planning clears evidence too');
bt.noteListed('ready', 2, T0 + 6);
ok(bt.listedAt('ready', 2) === null, 'a not-planned pane cannot become ready');
bt.plan('ready', T0 + 7);
bt.noteListed('ready', 3, T0 + 8);
bt.drop('ready');
ok(bt.listedAt('ready', 3) === null, 'pane end drops startup evidence');
ok(bt.CODEX_STARTUP_WAIT_MS === 30_000, 'Codex startup fallback is fixed at thirty seconds');
bt.plan('deadline', T0);
ok(bt.startupDeadline('deadline') === T0 + 30_000, 'fallback is measured from launch, not the first room line');
bt.plan('deadline', T0 + 10);
ok(bt.startupDeadline('deadline') === T0 + 30_010, 'a fresh plan owns a fresh deadline');
bt.drop('deadline');
ok(bt.startupDeadline('deadline') === null, 'pane end drops the deadline');
console.log(`\nPASS ${passed} FAIL ${failed}`);
process.exit(failed ? 1 : 0);
