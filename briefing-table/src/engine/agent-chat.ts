/** Panes whose hook arrived without the turn text (so the reason can say so). */
const hookGaps = new Map<string, Set<string>>();
export function noteHookGap(paneid: string, event: string): void {
  let s = hookGaps.get(paneid);
  if (!s) {
    s = new Set();
    hookGaps.set(paneid, s);
  }
  s.add(event);
}
export function recordHookTurn(paneid: string, role: 'user' | 'agent', text: string): void {
  let t = text.trim();
  if (role === 'user') {
    t = t.replace(PLAIN_FRAME_RE, ''); // a voice frame stays: pageCodex reads it back
  }
  if (!t) {
    return;
  }
  table.appendPaneChat(paneid, role, t);
  hookGaps.get(paneid)?.delete(role === 'user' ? 'UserPromptSubmit' : 'Stop');
}
export function forgetPane(paneid: string): void {
  hookGaps.delete(paneid);
}

export function pageCodex(paneid: string, q: { before?: string | null; after?: string | null; limit: number }): Pick<ChatPage, 'items' | 'before' | 'latest'> {
  const num = (s: string | null | undefined): number | undefined => (s && /^\d+$/.test(s) ? Number(s) : undefined);
  const r = table.listPaneChat(paneid, { before: num(q.before), after: num(q.after), limit: q.limit });
  const items: ChatItem[] = [];
  for (const row of r.rows) {
    const c = row.role === 'user' ? cleanUserText(row.text) : { text: row.text };
    if (!c) {
      continue;
    }
    if ('marker' in c) {
      items.push({ id: `c${row.seq}`, role: 'system', text: c.marker, ts: row.ts });
      continue;
    }
    items.push({ id: `c${row.seq}`, role: row.role, text: c.text, ts: row.ts, ...(c.files ? { files: c.files } : {}), ...('via' in c && c.via ? { meta: { via: c.via } } : {}) });
  }
  return {
    items,
    before: r.more && r.rows.length ? String(r.rows[0].seq) : null,
    latest: r.latest === null ? null : String(r.latest),
  };
}

